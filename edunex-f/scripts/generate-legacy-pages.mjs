import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const sourceDir = fs.existsSync(path.join(root, "legacy-html"))
  ? path.join(root, "legacy-html")
  : root;
const generatedDir = path.join(root, "src", "generated-pages");

const pageFiles = fs.readdirSync(sourceDir)
  .filter((file) => file.endsWith(".html") && file !== "react-index.html")
  .sort();

function matchFirst(pattern, text, fallback = "") {
  return text.match(pattern)?.[1] || fallback;
}

function escapeTemplate(value) {
  return String(value)
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

function extractScripts(html) {
  return [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)].map((match) => {
    const attrs = match[1] || "";
    const src = attrs.match(/\bsrc=(["'])(.*?)\1/i)?.[2] || "";
    return src ? { src } : null;
  }).filter((script) => {
    if (!script?.src) return false;
    return true;
  });
}

function extractStylesheets(head) {
  return [...head.matchAll(/<link\b([^>]*rel=(["'])stylesheet\2[^>]*)>/gi)]
    .map((match) => match[1].match(/\bhref=(["'])(.*?)\1/i)?.[2])
    .filter(Boolean)
    .filter((href) => !/^https?:\/\//i.test(href) && !href.startsWith("//"));
}

function extractStyles(head) {
  return [...head.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)]
    .map((match) => match[1])
    .join("\n\n");
}

const entries = pageFiles.map((file) => {
  const html = fs.readFileSync(path.join(sourceDir, file), "utf8");
  const head = matchFirst(/<head\b[^>]*>([\s\S]*?)<\/head>/i, html);
  const title = matchFirst(/<title\b[^>]*>([\s\S]*?)<\/title>/i, head, "EduNex AI").trim();
  const lang = html.match(/<html\b[^>]*lang=(["'])(.*?)\1/i)?.[2] || "en";
  return {
    file,
    page: {
      title,
      lang,
      stylesheets: extractStylesheets(head),
      styles: extractStyles(head),
      scripts: extractScripts(html).filter((script) => {
        if (!script.src) return true;
        return !/^https?:\/\//i.test(script.src) && !script.src.startsWith("//");
      }),
    },
  };
});

fs.rmSync(generatedDir, { recursive: true, force: true });
fs.mkdirSync(generatedDir, { recursive: true });

function pageModuleName(file) {
  return `${file}.js`;
}

function pageModuleText(page) {
  const scripts = page.scripts.map((script) => script.src
    ? `{ src: \`${escapeTemplate(script.src)}\` }`
    : "").filter(Boolean).join(",\n    ");
  const stylesheets = page.stylesheets.map((href) => `\`${escapeTemplate(href)}\``).join(", ");
  const scriptBlock = scripts ? `\n    ${scripts}\n  ` : "";
  return `/* This file is generated by scripts/generate-legacy-pages.mjs. */\n` +
    `export const page = {\n` +
    `  title: \`${escapeTemplate(page.title)}\`,\n` +
    `  lang: \`${escapeTemplate(page.lang)}\`,\n` +
    `  stylesheets: [${stylesheets}],\n` +
    `  styles: \`${escapeTemplate(page.styles)}\`,\n` +
    `  scripts: [${scriptBlock}],\n` +
    `};\n\n` +
    `export default page;\n`;
}

for (const { file, page } of entries) {
  fs.writeFileSync(path.join(generatedDir, pageModuleName(file)), pageModuleText(page));
}

console.log(`Generated ${entries.length} React page style/runtime metadata modules.`);
